//! The parts of a document that the tool writes: the components table and the navigation line.

use crate::elements::registry::Registry;

/// One element of an example, for the components table.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Row {
    /// Position in the file (the number used by the checks).
    pub index: usize,
    /// Class of the element.
    pub class: String,
    /// What the element is (`resistor`), as the program names it.
    pub kind: String,
    /// The values of its fields: `Resistance = 1k; ...`.
    pub values: String,
}

/// The elements of the example (wires left out), or `None` when the example does not load without
/// errors in this build (a family is left out).
pub fn component_rows(example_text: &str, registry: &Registry) -> Option<Vec<Row>> {
    let parsed = crate::format::parser::parse(example_text, registry);
    if !parsed.errors.is_empty() {
        return None;
    }
    let mut rows = Vec::new();
    for (index, e) in parsed.circuit.elements.iter().enumerate() {
        if e.class_name() == "WireElm" {
            continue;
        }
        let kind = e.elm_type().map(|k| crate::locale::ls(&k)).unwrap_or_default();
        let mut parts = Vec::new();
        for n in 0..40 {
            let Some(ei) = e.get_edit_info(n) else { break };
            if ei.button.is_some() {
                continue;
            }
            // the label of a checkbox is kept in its text
            let label = if ei.checkbox.is_some() {
                ei.text.clone().unwrap_or_default()
            } else {
                ei.name.clone()
            };
            let name = crate::locale::ls(&label);
            let text = if let Some(on) = ei.checkbox {
                (if on { "sim" } else { "não" }).to_string()
            } else if let Some(options) = &ei.choice {
                options.get(ei.choice_index).cloned().unwrap_or_default()
            } else if let Some(t) = &ei.text {
                t.replace('\n', " ").chars().take(60).collect()
            } else {
                crate::elements::units::short_unit_text(ei.value, "")
            };
            parts.push(format!("{name} = {text}"));
        }
        rows.push(Row { index, class: e.class_name().to_string(), kind, values: parts.join("; ") });
    }
    Some(rows)
}

/// The components table for the example, or `None` when it does not load in this build.
pub fn components_region(example_text: &str, registry: &Registry) -> Option<String> {
    let rows = component_rows(example_text, registry)?;
    let cell = |s: &str| s.replace('|', "\\|");
    let mut out =
        String::from("| N.º | Tipo | Elemento | Valores |\n|----:|------|----------|---------|\n");
    for r in &rows {
        out.push_str(&format!(
            "| {} | `{}` | {} | {} |\n",
            r.index,
            r.class,
            cell(&r.kind),
            cell(&r.values)
        ));
    }
    Some(out.trim_end().to_string())
}

/// The picture of the schematic, generated by `exdocs sync` into `img/<stem>.svg`.
pub fn figure_region(stem: &str) -> String {
    format!("![Esquema do circuito](img/{stem}.svg)")
}

/// `doc` with the `esquema` region put right under the `## O circuito` heading when it has none.
pub fn ensure_figure_region(doc: &str) -> String {
    if doc.contains("<!-- esquema:inicio -->") {
        return doc.to_string();
    }
    let heading = "\n## O circuito\n";
    match doc.find(heading) {
        None => doc.to_string(),
        Some(at) => {
            let end = at + heading.len();
            format!(
                "{}\n<!-- esquema:inicio -->\n<!-- esquema:fim -->\n{}",
                &doc[..end],
                &doc[end..]
            )
        }
    }
}

/// The navigation line: the index, and the previous and next example of the category.
pub fn navigation_region(prev: Option<(&str, &str)>, next: Option<(&str, &str)>) -> String {
    let mut parts = vec!["[Índice](README.md)".to_string()];
    if let Some((stem, title)) = prev {
        parts.push(format!("[Anterior: {title}]({stem}.md)"));
    }
    if let Some((stem, title)) = next {
        parts.push(format!("[Próximo: {title}]({stem}.md)"));
    }
    parts.join(" · ")
}

/// The text between the markers of region `name` (`<!-- name:inicio -->` … `<!-- name:fim -->`).
pub fn get_region<'a>(doc: &'a str, name: &str) -> Option<&'a str> {
    let (start, end) = (format!("<!-- {name}:inicio -->"), format!("<!-- {name}:fim -->"));
    let from = doc.find(&start)? + start.len();
    let to = from + doc[from..].find(&end)?;
    Some(doc[from..to].trim_matches('\n'))
}

/// `doc` with the region `name` replaced by `body`; `None` when the markers are not there.
pub fn replace_region(doc: &str, name: &str, body: &str) -> Option<String> {
    let (start, end) = (format!("<!-- {name}:inicio -->"), format!("<!-- {name}:fim -->"));
    let from = doc.find(&start)? + start.len();
    let to = from + doc[from..].find(&end)?;
    Some(format!("{}\n{body}\n{}", &doc[..from], &doc[to..]))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[cfg(all(feature = "passive", feature = "sources"))]
    const RC: &str = "$ 1 0.000005 10 50 5 50 5e-11\nv 0 128 0 0 0 0 40 5 0 0 0.5\nr 0 0 64 0 0 1000\nr 64 0 64 128 0 3000\nw 64 128 0 128 0\n";

    #[cfg(all(feature = "passive", feature = "sources"))]
    #[test]
    fn the_components_table_lists_each_element_but_the_wires() {
        let reg = Registry::standard();
        let rows = component_rows(RC, &reg).unwrap();
        assert_eq!(
            rows.iter().map(|r| (r.index, r.class.as_str())).collect::<Vec<_>>(),
            [(0, "VoltageElm"), (1, "ResistorElm"), (2, "ResistorElm")]
        );
        assert!(rows[1].values.contains("1k"), "{:?}", rows[1]);
        assert!(rows[2].values.contains("3k"), "{:?}", rows[2]);
        let table = components_region(RC, &reg).unwrap();
        assert!(table.starts_with("| N.º | Tipo | Elemento | Valores |"), "{table}");
        assert_eq!(table.lines().count(), 2 + 3, "{table}");
        assert!(table.contains("ResistorElm"));
        // the same text twice
        assert_eq!(table, components_region(RC, &reg).unwrap());
    }

    #[test]
    fn an_example_that_does_not_load_is_skipped_not_failed() {
        let reg = Registry::standard();
        assert_eq!(component_rows("$ 1 0.000005 10 50 5 50 5e-11\nzzz 0 0 1 1 0\n", &reg), None);
        assert_eq!(components_region("$ 1 0.000005 10 50 5 50 5e-11\nzzz 0 0 1 1 0\n", &reg), None);
    }

    #[test]
    fn the_navigation_line_has_the_index_and_the_neighbours() {
        assert_eq!(
            navigation_region(Some(("a", "Alpha")), Some(("c", "Gamma"))),
            "[Índice](README.md) · [Anterior: Alpha](a.md) · [Próximo: Gamma](c.md)"
        );
        assert_eq!(
            navigation_region(None, Some(("c", "Gamma"))),
            "[Índice](README.md) · [Próximo: Gamma](c.md)"
        );
        assert_eq!(navigation_region(None, None), "[Índice](README.md)");
    }

    #[test]
    fn the_figure_region_goes_under_the_circuit_heading_once() {
        let doc = "# T\n\n## O circuito\n\nTexto.\n";
        let with = ensure_figure_region(doc);
        assert!(with.contains("## O circuito\n\n<!-- esquema:inicio -->\n<!-- esquema:fim -->\n"));
        assert_eq!(ensure_figure_region(&with), with);
        let filled = replace_region(&with, "esquema", &figure_region("rc")).unwrap();
        assert!(filled.contains("![Esquema do circuito](img/rc.svg)"));
        assert_eq!(ensure_figure_region("sem seção"), "sem seção");
    }

    #[test]
    fn a_region_is_replaced_and_the_text_around_it_is_kept() {
        let doc = "antes\n<!-- navegacao:inicio -->\nvelho\n<!-- navegacao:fim -->\ndepois\n";
        assert_eq!(get_region(doc, "navegacao"), Some("velho"));
        let new = replace_region(doc, "navegacao", "novo").unwrap();
        assert_eq!(new, "antes\n<!-- navegacao:inicio -->\nnovo\n<!-- navegacao:fim -->\ndepois\n");
        assert_eq!(
            replace_region(&new, "navegacao", "novo").unwrap(),
            new,
            "a second run changes nothing"
        );
        assert_eq!(replace_region(doc, "componentes", "x"), None);
        assert_eq!(get_region(doc, "componentes"), None);
    }
}
